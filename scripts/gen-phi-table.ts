// Prints PHI2[i] = 2*(1-Φ(i*0.05)) in bps (min 1) as a Rust const.
// bun scripts/gen-phi-table.ts > contracts/riptide/src/phi.rs
const pdf = (x: number) => Math.exp(-x * x / 2) / Math.sqrt(2 * Math.PI);
const tail2 = (z: number) => { // 1 - 2*∫0^z φ, Simpson
  const n = 20000, h = z / n;
  let s = pdf(0) + pdf(z);
  for (let i = 1; i < n; i++) s += (i % 2 ? 4 : 2) * pdf(i * h);
  return 1 - 2 * (s * h / 3);
};
const vals = Array.from({ length: 81 }, (_, i) => Math.max(1, Math.round(tail2(i * 0.05) * 10000)));
console.log(`// Generated by scripts/gen-phi-table.ts. PHI2[i] = 2*(1-Phi(i*0.05)) in bps, min 1.
pub const PHI2: [u32; 81] = [
${vals.map((v, i) => `    ${v},${i % 5 === 0 ? ` // z=${(i * 0.05).toFixed(2)}` : ""}`).join("\n")}
];`);
